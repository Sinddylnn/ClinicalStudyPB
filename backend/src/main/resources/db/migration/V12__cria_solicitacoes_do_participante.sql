-- <-------------------CONFIRMAÇÃO DE PRESENÇA (RF19)------------------->
-- A confirmação é só uma data guardada na própria visita; a situação continua AGENDADA
-- Visitas existentes iniciam sem confirmação
ALTER TABLE visitas_agendadas
    ADD COLUMN presenca_confirmada_em TIMESTAMP WITH TIME ZONE;


-- <-------------------SOLICITAÇÕES DE REAGENDAMENTO (RF19)------------------->
CREATE TABLE solicitacoes_reagendamento (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    visita_agendada_id BIGINT NOT NULL REFERENCES visitas_agendadas(id),
    -- Data da visita no momento do pedido; preserva o histórico depois de uma aprovação
    data_hora_original TIMESTAMP WITH TIME ZONE NOT NULL,
    data_hora_desejada TIMESTAMP WITH TIME ZONE NOT NULL,
    motivo VARCHAR(500)
        CHECK (motivo IS NULL OR CHAR_LENGTH(BTRIM(motivo)) BETWEEN 1 AND 500),
    situacao VARCHAR(20) NOT NULL DEFAULT 'PENDENTE'
        CHECK (situacao IN ('PENDENTE', 'APROVADA', 'RECUSADA', 'CANCELADA')),
    solicitada_em TIMESTAMP WITH TIME ZONE NOT NULL,
    -- Coordenador que respondeu; fica vazio no cancelamento automático
    respondida_por_id BIGINT REFERENCES usuarios(id),
    -- Momento em que o pedido deixou de ser PENDENTE (resposta ou cancelamento)
    encerrada_em TIMESTAMP WITH TIME ZONE,
    -- Nova data registrada pelo coordenador, que pode diferir da desejada
    data_hora_aprovada TIMESTAMP WITH TIME ZONE,
    justificativa_recusa VARCHAR(500),
    CONSTRAINT ck_solicitacoes_reagendamento_resposta
        CHECK (
            (situacao = 'PENDENTE'
                AND respondida_por_id IS NULL
                AND encerrada_em IS NULL
                AND data_hora_aprovada IS NULL
                AND justificativa_recusa IS NULL)
            OR
            (situacao = 'APROVADA'
                AND respondida_por_id IS NOT NULL
                AND encerrada_em IS NOT NULL
                AND data_hora_aprovada IS NOT NULL
                AND justificativa_recusa IS NULL)
            OR
            (situacao = 'RECUSADA'
                AND respondida_por_id IS NOT NULL
                AND encerrada_em IS NOT NULL
                AND data_hora_aprovada IS NULL
                AND justificativa_recusa IS NOT NULL
                AND CHAR_LENGTH(BTRIM(justificativa_recusa)) BETWEEN 1 AND 500)
            OR
            (situacao = 'CANCELADA'
                AND respondida_por_id IS NULL
                AND encerrada_em IS NOT NULL
                AND data_hora_aprovada IS NULL
                AND justificativa_recusa IS NULL)
        )
);

-- Só um pedido pendente por visita, mesmo com requisições simultâneas
CREATE UNIQUE INDEX uk_solicitacoes_reagendamento_pendente
    ON solicitacoes_reagendamento (visita_agendada_id)
    WHERE situacao = 'PENDENTE';
CREATE INDEX idx_solicitacoes_reagendamento_visita
    ON solicitacoes_reagendamento (visita_agendada_id, solicitada_em);


-- <-------------------SOLICITAÇÕES DE RETIRADA VOLUNTÁRIA (RF20)------------------->
CREATE TABLE solicitacoes_retirada (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    participacao_id BIGINT NOT NULL REFERENCES participacoes(id),
    -- O motivo é opcional: o participante não precisa justificar a saída
    motivo VARCHAR(500)
        CHECK (motivo IS NULL OR CHAR_LENGTH(BTRIM(motivo)) BETWEEN 1 AND 500),
    -- Não existe recusa da retirada voluntária
    situacao VARCHAR(20) NOT NULL DEFAULT 'PENDENTE'
        CHECK (situacao IN ('PENDENTE', 'CONCLUIDA')),
    solicitada_em TIMESTAMP WITH TIME ZONE NOT NULL,
    respondida_por_id BIGINT REFERENCES usuarios(id),
    encerrada_em TIMESTAMP WITH TIME ZONE,
    CONSTRAINT ck_solicitacoes_retirada_resposta
        CHECK (
            (situacao = 'PENDENTE'
                AND respondida_por_id IS NULL
                AND encerrada_em IS NULL)
            OR
            (situacao = 'CONCLUIDA'
                AND respondida_por_id IS NOT NULL
                AND encerrada_em IS NOT NULL)
        )
);

-- Só um pedido pendente por participação, mesmo com requisições simultâneas
CREATE UNIQUE INDEX uk_solicitacoes_retirada_pendente
    ON solicitacoes_retirada (participacao_id)
    WHERE situacao = 'PENDENTE';
CREATE INDEX idx_solicitacoes_retirada_participacao
    ON solicitacoes_retirada (participacao_id, solicitada_em);

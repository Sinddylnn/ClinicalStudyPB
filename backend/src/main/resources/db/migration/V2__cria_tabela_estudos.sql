-- ============================================================
-- V2 - Criação da tabela de estudos
-- ============================================================
-- Estrutura inicial utilizada para armazenar os estudos
-- clínicos cadastrados no ClinicalStudyPB.
-- ============================================================

CREATE TABLE estudos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    titulo VARCHAR(150) NOT NULL,

    objetivo VARCHAR(2000) NOT NULL,

    responsavel_id BIGINT NOT NULL,

    data_inicio DATE NOT NULL,

    data_fim DATE NOT NULL,

    limite_participantes INTEGER NOT NULL,

    estado VARCHAR(20) NOT NULL DEFAULT 'PLANEJAMENTO',

    -- O pesquisador responsável deve existir na tabela de usuários.
    CONSTRAINT fk_estudos_responsavel
        FOREIGN KEY (responsavel_id)
        REFERENCES usuarios (id),

    -- Evita títulos vazios ou formados apenas por espaços.
    CONSTRAINT ck_estudos_titulo
        CHECK (CHAR_LENGTH(BTRIM(titulo)) BETWEEN 1 AND 150),

    -- Evita objetivos vazios ou formados apenas por espaços.
    CONSTRAINT ck_estudos_objetivo
        CHECK (CHAR_LENGTH(BTRIM(objetivo)) BETWEEN 1 AND 2000),

    -- A data final não pode ser anterior à data inicial.
    CONSTRAINT ck_estudos_periodo
        CHECK (data_fim >= data_inicio),

    -- Todo estudo deve possuir pelo menos uma vaga.
    CONSTRAINT ck_estudos_limite_participantes
        CHECK (limite_participantes > 0),

    -- Restringe o estado aos valores previstos pelo sistema.
    CONSTRAINT ck_estudos_estado
        CHECK (
            estado IN (
                'PLANEJAMENTO',
                'RECRUTAMENTO',
                'EXECUCAO',
                'ENCERRADO'
            )
        )
);

-- <-------------------SITUAÇÃO E RETIRADA DA PARTICIPAÇÃO------------------->
ALTER TABLE participacoes
    ADD COLUMN situacao VARCHAR(20) NOT NULL DEFAULT 'ATIVA',
    ADD COLUMN data_retirada TIMESTAMP WITH TIME ZONE,
    ADD COLUMN motivo_retirada VARCHAR(500),
    ADD COLUMN retirada_por_id BIGINT REFERENCES usuarios(id),
    ADD CONSTRAINT ck_participacao_situacao
        CHECK (situacao IN ('ATIVA', 'RETIRADA')),
    ADD CONSTRAINT ck_participacao_retirada
        CHECK (
            (situacao = 'ATIVA'
                AND data_retirada IS NULL
                AND motivo_retirada IS NULL
                AND retirada_por_id IS NULL)
            OR
            (situacao = 'RETIRADA'
                AND data_retirada IS NOT NULL
                AND motivo_retirada IS NOT NULL
                AND CHAR_LENGTH(BTRIM(motivo_retirada)) BETWEEN 1 AND 500
                AND retirada_por_id IS NOT NULL)
        );

-- <-------------------VISITAS AGENDADAS------------------->
CREATE TABLE visita_agendada (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    participacao_id BIGINT NOT NULL REFERENCES participacoes(id),
    visita_prevista_id BIGINT NOT NULL REFERENCES visitas_previstas(id),
    data_hora TIMESTAMP WITH TIME ZONE NOT NULL,
    situacao VARCHAR(20) NOT NULL DEFAULT 'AGENDADA'
        CHECK (situacao IN ('AGENDADA', 'REALIZADA', 'AUSENTE', 'CANCELADA')),
    motivo VARCHAR(500),
    registrado_por_id BIGINT REFERENCES usuarios(id),
    registrado_em TIMESTAMP WITH TIME ZONE,
    CONSTRAINT ck_visita_agendada_motivo
        CHECK (
            (situacao = 'AGENDADA' AND motivo IS NULL)
            OR
            (situacao = 'CANCELADA'
                AND motivo IS NOT NULL
                AND CHAR_LENGTH(BTRIM(motivo)) BETWEEN 1 AND 500)
            OR
            (situacao = 'AUSENTE'
                AND (motivo IS NULL OR CHAR_LENGTH(BTRIM(motivo)) BETWEEN 1 AND 500))
            OR
            (situacao = 'REALIZADA' AND motivo IS NULL)
        ),
    CONSTRAINT ck_visita_agendada_registro
        CHECK (
            (situacao = 'AGENDADA' AND registrado_por_id IS NULL AND registrado_em IS NULL)
            OR
            (situacao <> 'AGENDADA' AND registrado_por_id IS NOT NULL AND registrado_em IS NOT NULL)
        )
);

CREATE UNIQUE INDEX uk_visita_agendada_pendente
    ON visita_agendada (participacao_id, visita_prevista_id)
    WHERE situacao = 'AGENDADA';
CREATE INDEX idx_visita_agendada_participacao
    ON visita_agendada (participacao_id, data_hora);

-- <-------------------RESULTADOS DE ATIVIDADES------------------->
CREATE TABLE resultado_atividade (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    visita_agendada_id BIGINT NOT NULL REFERENCES visita_agendada(id),
    atividade_prevista_id BIGINT NOT NULL REFERENCES atividades_previstas(id),
    texto VARCHAR(1000) NOT NULL
        CHECK (CHAR_LENGTH(BTRIM(texto)) BETWEEN 1 AND 1000),
    registrado_por_id BIGINT NOT NULL REFERENCES usuarios(id),
    registrado_em TIMESTAMP WITH TIME ZONE NOT NULL,
    atualizado_por_id BIGINT REFERENCES usuarios(id),
    atualizado_em TIMESTAMP WITH TIME ZONE,
    CONSTRAINT uk_resultado_atividade_visita UNIQUE (visita_agendada_id, atividade_prevista_id),
    CONSTRAINT ck_resultado_atividade_atualizacao
        CHECK ((atualizado_por_id IS NULL) = (atualizado_em IS NULL))
);

-- <-------------------HISTÓRICO DE CORREÇÕES DE VISITAS------------------->
CREATE TABLE correcao_visita (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    visita_agendada_id BIGINT NOT NULL REFERENCES visita_agendada(id),
    situacao_anterior VARCHAR(20) NOT NULL
        CHECK (situacao_anterior IN ('REALIZADA', 'AUSENTE', 'CANCELADA')),
    situacao_nova VARCHAR(20) NOT NULL
        CHECK (situacao_nova IN ('REALIZADA', 'AUSENTE', 'CANCELADA')),
    justificativa VARCHAR(500) NOT NULL
        CHECK (CHAR_LENGTH(BTRIM(justificativa)) BETWEEN 1 AND 500),
    corrigida_por_id BIGINT NOT NULL REFERENCES usuarios(id),
    corrigida_em TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT ck_correcao_visita_situacoes
        CHECK (situacao_anterior <> situacao_nova)
);

CREATE INDEX idx_correcao_visita_visita
    ON correcao_visita (visita_agendada_id, corrigida_em);

-- <-------------------AVALIACOES DE ELEGIBILIDADE------------------->

CREATE TABLE avaliacoes_elegibilidade (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    candidato_id BIGINT NOT NULL UNIQUE
        REFERENCES candidatos(id),

    avaliado_por_id BIGINT NOT NULL
        REFERENCES usuarios(id),

    avaliado_em TIMESTAMP WITHOUT TIME ZONE NOT NULL
);

-- <-------------------RESPOSTAS DOS CRITERIOS------------------->

CREATE TABLE respostas_elegibilidade (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    avaliacao_id BIGINT NOT NULL
        REFERENCES avaliacoes_elegibilidade(id) ON DELETE CASCADE,

    criterio_id BIGINT NOT NULL
        REFERENCES criterios(id),

    resposta VARCHAR(15) NOT NULL
        CHECK (resposta IN (
            'ATENDIDO',
            'NAO_ATENDIDO',
            'PRESENTE',
            'AUSENTE'
        )),

    CONSTRAINT uk_respostas_avaliacao_criterio
        UNIQUE (avaliacao_id, criterio_id)
);

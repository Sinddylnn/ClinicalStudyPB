-- <-------------------CONSENTIMENTO SIMULADO E SUAS CORREÇÕES------------------->
CREATE TABLE consentimentos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    candidato_id BIGINT NOT NULL REFERENCES candidatos(id),
    resposta VARCHAR(10) NOT NULL CHECK (resposta IN ('ACEITOU', 'RECUSOU')),
    observacao VARCHAR(500),
    registrado_por_id BIGINT NOT NULL REFERENCES usuarios(id),
    registrado_em TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT ck_consentimento_observacao
        CHECK (observacao IS NULL OR CHAR_LENGTH(BTRIM(observacao)) BETWEEN 1 AND 500)
);
CREATE INDEX idx_consentimentos_candidato_id ON consentimentos (candidato_id, id DESC);

-- <-------------------PROTOCOLO E CRITÉRIOS------------------->
-- Base necessária para verificar o RF07 (gerenciar estados de estudo - Pesquisador) com registros reais.
CREATE TABLE protocolos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    estudo_id BIGINT NOT NULL UNIQUE REFERENCES estudos(id),
    sem_criterios_exclusao BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE TABLE criterios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    protocolo_id BIGINT NOT NULL REFERENCES protocolos(id),
    tipo VARCHAR(10) NOT NULL CHECK (tipo IN ('INCLUSAO', 'EXCLUSAO')),
    descricao VARCHAR(1000) NOT NULL CHECK (CHAR_LENGTH(BTRIM(descricao)) BETWEEN 1 AND 1000)
);
CREATE INDEX idx_criterios_protocolo_tipo ON criterios(protocolo_id, tipo);

-- <-------------------MODELOS DE VISITAS E ATIVIDADES------------------->
CREATE TABLE visitas_previstas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    protocolo_id BIGINT NOT NULL REFERENCES protocolos(id),
    nome VARCHAR(150) NOT NULL CHECK (CHAR_LENGTH(BTRIM(nome)) BETWEEN 1 AND 150),
    descricao VARCHAR(1000),
    ordem INTEGER NOT NULL CHECK (ordem > 0),
    CONSTRAINT uk_visitas_previstas_protocolo_ordem UNIQUE (protocolo_id, ordem)
);

CREATE TABLE atividades_previstas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    visita_prevista_id BIGINT NOT NULL REFERENCES visitas_previstas(id) ON DELETE CASCADE,
    descricao VARCHAR(1000) NOT NULL CHECK (CHAR_LENGTH(BTRIM(descricao)) BETWEEN 1 AND 1000)
);
CREATE INDEX idx_atividades_previstas_visita ON atividades_previstas(visita_prevista_id);

-- <-------------------INCLUSÕES HISTÓRICAS------------------->
-- Não é um cadastro de candidatos nem um registro de consentimento.
-- RF11 deverá validar suas condições antes de criar a participação.
-- Uma retirada futura não deve excluir esta linha nem liberar outra vaga.
CREATE TABLE participacoes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    estudo_id BIGINT NOT NULL REFERENCES estudos(id),
    participante_id BIGINT NOT NULL REFERENCES usuarios(id),
    data_inclusao TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_participacoes_estudo_conta UNIQUE (estudo_id, participante_id)
);

-- <-------------------CANDIDATOS DOS ESTUDOS------------------->

CREATE TABLE candidatos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    estudo_id BIGINT NOT NULL REFERENCES estudos(id),

    nome VARCHAR(150) NOT NULL
        CHECK (CHAR_LENGTH(BTRIM(nome)) BETWEEN 1 AND 150),

    email VARCHAR(254) NOT NULL
        CHECK (CHAR_LENGTH(BTRIM(email)) BETWEEN 1 AND 254),

    elegibilidade VARCHAR(20) NOT NULL DEFAULT 'NAO_AVALIADO'
        CHECK (elegibilidade IN (
            'NAO_AVALIADO', 'INCOMPLETA', 'ELEGIVEL', 'INELEGIVEL'
        )),

    consentimento VARCHAR(20) NOT NULL DEFAULT 'PENDENTE'
        CHECK (consentimento IN (
            'PENDENTE', 'ACEITOU', 'RECUSOU'
        ))
);

-- Evita cadastrar o mesmo e-mail duas vezes no mesmo estudo.
CREATE UNIQUE INDEX uk_candidatos_estudo_email
    ON candidatos (estudo_id, LOWER(email));

-- Facilita a listagem de candidatos por estudo.
CREATE INDEX idx_candidatos_estudo
    ON candidatos (estudo_id);

-- ============================================================
-- V1 - Criação da tabela de usuários
-- ============================================================
-- Estrutura inicial utilizada para armazenar os usuários do
-- ClinicalStudyPB e seus respectivos perfis de acesso.
-- ============================================================

CREATE TABLE usuarios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    nome VARCHAR(255) NOT NULL,

    email VARCHAR(255) NOT NULL,

    senha_hash VARCHAR(255) NOT NULL,

    perfil VARCHAR(20) NOT NULL,

    ativo BOOLEAN NOT NULL DEFAULT TRUE,

    CONSTRAINT ck_usuarios_perfil
        CHECK (
            perfil IN (
                'ADMINISTRADOR',
                'PESQUISADOR',
                'COORDENADOR',
                'PARTICIPANTE'
            )
        )
);

-- Impede o cadastro de e-mails duplicados mesmo quando houver
-- diferença entre letras maiúsculas/minúsculas ou espaços
-- antes e depois do endereço.
CREATE UNIQUE INDEX uk_usuarios_email
    ON usuarios (LOWER(BTRIM(email)));
